private void loadArchiveTable() {
String sql = "SELECT * FROM archive ORDER BY deleted_at DESC";

try (PreparedStatement pst = con.prepareStatement(sql);
     ResultSet rs = pst.executeQuery()) {

    DefaultTableModel model = (DefaultTableModel) jTable3.getModel();
    model.setRowCount(0);

    while (rs.next()) {
        model.addRow(new Object[]{
            rs.getInt("archive_id"),
            rs.getString("id_number"),
            rs.getString("first_name"),
            rs.getString("middle_name"),
            rs.getString("last_name"),
            rs.getString("contact"),
            rs.getString("address"),
            rs.getString("vehicle_type"),
            rs.getString("plate_number"),
            rs.getString("color"),
            rs.getTimestamp("parking_in") != null 
                ? rs.getTimestamp("parking_in").toString() 
                : "",
            rs.getTimestamp("parking_out") != null 
                ? rs.getTimestamp("parking_out").toString() 
                : "",
            rs.getTimestamp("deleted_at") != null 
                ? rs.getTimestamp("deleted_at").toString() 
                : ""
        });
    }

} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this,
        "❌ Failed to load archive:\n" + ex.getMessage(),
        "Database Error",
        JOptionPane.ERROR_MESSAGE);
}
}

