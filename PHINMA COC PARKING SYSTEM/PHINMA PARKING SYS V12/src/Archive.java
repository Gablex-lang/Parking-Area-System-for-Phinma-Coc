    private void btnRestoreActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRestoreActionPerformed
       int selectedRow = jTable3.getSelectedRow();
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this,
            "Please select a record to restore from the archive.",
            "No Selection",
            JOptionPane.WARNING_MESSAGE);
        return;
    }

    int archiveId = (int) jTable3.getValueAt(selectedRow, 0);

    int confirm = JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to restore ALL records with the same ID number?",
        "Confirm Restore",
        JOptionPane.YES_NO_OPTION
    );
    if (confirm != JOptionPane.YES_OPTION) return;

    try {
        con.setAutoCommit(false);

        // --- Step 1: Get id_number for the selected archive row ---
        String idNumber = null;
        String findIdSQL = "SELECT id_number FROM archive WHERE archive_id = ?";
        try (PreparedStatement findPst = con.prepareStatement(findIdSQL)) {
            findPst.setInt(1, archiveId);
            try (ResultSet findRs = findPst.executeQuery()) {
                if (findRs.next()) {
                    idNumber = findRs.getString("id_number");
                } else {
                    JOptionPane.showMessageDialog(this, "Record not found in archive.");
                    con.setAutoCommit(true);
                    return;
                }
            }
        }

        // --- Step 2: Fetch all archive rows with same id_number ---
        String selectSQL = "SELECT * FROM archive WHERE id_number = ?";
        try (PreparedStatement selectPst = con.prepareStatement(selectSQL,
                ResultSet.TYPE_FORWARD_ONLY, ResultSet.CONCUR_READ_ONLY)) {

            selectPst.setString(1, idNumber);
            try (ResultSet rs = selectPst.executeQuery()) {
                boolean hasRows = false;

                while (rs.next()) {
                    hasRows = true;

                    // --- DRIVER: check if exists ---
                    int driverId = 0;
                    String checkDriverSQL = "SELECT driver_id FROM driver WHERE id_number = ?";
                    try (PreparedStatement chkDriver = con.prepareStatement(checkDriverSQL)) {
                        chkDriver.setString(1, rs.getString("id_number"));
                        try (ResultSet rDriver = chkDriver.executeQuery()) {
                            if (rDriver.next()) {
                                driverId = rDriver.getInt("driver_id");
                            }
                        }
                    }

                    // If not found, insert into DRIVER
                    if (driverId == 0) {
                        String insertDriverSQL =
                            "INSERT INTO driver (id_number, first_name, middle_name, last_name, contact, address) " +
                            "VALUES (?, ?, ?, ?, ?, ?)";
                        try (PreparedStatement pstDriver = con.prepareStatement(insertDriverSQL, Statement.RETURN_GENERATED_KEYS)) {
                            pstDriver.setString(1, rs.getString("id_number"));
                            pstDriver.setString(2, rs.getString("first_name"));
                            pstDriver.setString(3, rs.getString("middle_name"));
                            pstDriver.setString(4, rs.getString("last_name"));
                            pstDriver.setString(5, rs.getString("contact"));
                            pstDriver.setString(6, rs.getString("address"));
                            pstDriver.executeUpdate();
                            try (ResultSet genDriver = pstDriver.getGeneratedKeys()) {
                                if (genDriver.next()) driverId = genDriver.getInt(1);
                            }
                        }
                    }

                    // --- VEHICLE: check existence by plate number ---
                    int vehicleId = 0;
                    String plateNumber = rs.getString("plate_number");
                    if (plateNumber != null && !plateNumber.trim().isEmpty()) {
                        String checkVehicleSQL = "SELECT vehicle_id FROM vehicle WHERE plate_number = ?";
                        try (PreparedStatement chkVehicle = con.prepareStatement(checkVehicleSQL)) {
                            chkVehicle.setString(1, plateNumber);
                            try (ResultSet rVehicle = chkVehicle.executeQuery()) {
                                if (rVehicle.next()) {
                                    vehicleId = rVehicle.getInt("vehicle_id");
                                }
                            }
                        }
                    }

                    // If not found, insert new VEHICLE
                    if (vehicleId == 0) {
                        String insertVehicleSQL =
                            "INSERT INTO vehicle (driver_id, vehicle_type, plate_number, color) VALUES (?, ?, ?, ?)";
                        try (PreparedStatement pstVehicle = con.prepareStatement(insertVehicleSQL, Statement.RETURN_GENERATED_KEYS)) {
                            pstVehicle.setInt(1, driverId);
                            pstVehicle.setString(2, rs.getString("vehicle_type"));
                            pstVehicle.setString(3, rs.getString("plate_number"));
                            pstVehicle.setString(4, rs.getString("color"));
                            pstVehicle.executeUpdate();
                            try (ResultSet genVehicle = pstVehicle.getGeneratedKeys()) {
                                if (genVehicle.next()) vehicleId = genVehicle.getInt(1);
                            }
                        }
                    } else {
                        // Update driver_id link if needed
                        String updateVehicleDriverSQL = "UPDATE vehicle SET driver_id = ? WHERE vehicle_id = ? AND driver_id <> ?";
                        try (PreparedStatement updt = con.prepareStatement(updateVehicleDriverSQL)) {
                            updt.setInt(1, driverId);
                            updt.setInt(2, vehicleId);
                            updt.setInt(3, driverId);
                            updt.executeUpdate();
                        }
                    }

                    // --- PARKINGTRANSACTION: restore record ---
                    String insertTransactionSQL =
                        "INSERT INTO parkingtransaction (vehicle_id, slot_number, parking_in, parking_out) " +
                        "VALUES (?, ?, ?, ?)";
                    try (PreparedStatement pstTrans = con.prepareStatement(insertTransactionSQL)) {
                        pstTrans.setInt(1, vehicleId);
                        pstTrans.setString(2, rs.getString("slot_number"));
                        pstTrans.setTimestamp(3, rs.getTimestamp("parking_in"));
                        pstTrans.setTimestamp(4, rs.getTimestamp("parking_out"));
                        pstTrans.executeUpdate();
                    }
                }

                if (!hasRows) {
                    JOptionPane.showMessageDialog(this,
                        "No archive records found with ID number: " + idNumber,
                        "Nothing to Restore",
                        JOptionPane.INFORMATION_MESSAGE);
                    con.setAutoCommit(true);
                    return;
                }
            }
        }

        // --- Step 3: Delete restored rows from archive ---
        String deleteSQL = "DELETE FROM archive WHERE id_number = ?";
        try (PreparedStatement pstDelete = con.prepareStatement(deleteSQL)) {
            pstDelete.setString(1, idNumber);
            pstDelete.executeUpdate();
        }

        con.commit();
        con.setAutoCommit(true);

        JOptionPane.showMessageDialog(this,
            "✅ All records with ID number " + idNumber + " successfully restored.",
            "Restore Successful",
            JOptionPane.INFORMATION_MESSAGE);

        loadArchiveTable(); // refresh archive view

    } catch (SQLException ex) {
        try { con.rollback(); } catch (SQLException ignore) {}
        JOptionPane.showMessageDialog(this,
            "❌ Restore failed:\n" + ex.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE);
        try { con.setAutoCommit(true); } catch (SQLException ignore) {}
    }
    }//GEN-LAST:event_btnRestoreActionPerformed

