    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
    if (con == null) {
        JOptionPane.showMessageDialog(this, "Database not connected");
        return;
    }

    // ✅ Get username & password
    String username = txtUser.getText().trim();
    String password = new String(txtPass.getPassword());

    if (username.isEmpty() || password.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in all fields.");
        return;
    }

    // ✅ SQL query to verify credentials
    String sql = "SELECT * FROM users WHERE username=? AND password=?";
    try (PreparedStatement pst = con.prepareStatement(sql)) {
        pst.setString(1, username);
        pst.setString(2, password);
        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            // ✅ Close the login form first
            this.dispose();

            // ✅ Check if user is admin or regular user
            if (username.toLowerCase().startsWith("admin")) {
                JOptionPane.showMessageDialog(this, "Welcome, Admin!");
                new Loading("admin").setVisible(true);  // shows loading, then Parking.java
            } else {
                
                new Loading("user").setVisible(true);   // shows loading, then Parking_1.java
            }
        } else {
            JOptionPane.showMessageDialog(this, "Invalid Username or Password");
        }

    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this,
            "Database Error: " + ex.getMessage(),
            "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnLoginActionPerformed

